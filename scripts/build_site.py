#!/usr/bin/env python3
"""Generate the Astro Lab's dependency-free static HTML pages."""

from __future__ import annotations

import argparse
import html
import json
import os
import sys
from pathlib import Path
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "data" / "site.json"


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def load_data() -> dict:
    return json.loads(DATA_PATH.read_text(encoding="utf-8"))


def href(output_path: str, target: str) -> str:
    if urlparse(target).scheme or target.startswith(("mailto:", "#")):
        return target
    start = (ROOT / output_path).parent
    return os.path.relpath(ROOT / target, start=start).replace(os.sep, "/")


def public_url(output_path: str) -> str:
    relative = output_path.removesuffix("index.html")
    return f"https://activities.tjhsst.edu/astro/{relative}"


def projects_for_year(data: dict, year_slug: str) -> list[dict]:
    return [project for project in data["projects"] if project["year"] == year_slug]


def year_definition(data: dict, year_slug: str) -> dict:
    return next(year for year in data["years"] if year["slug"] == year_slug)


def noun(count: int, singular: str, plural: str | None = None) -> str:
    return singular if count == 1 else (plural or f"{singular}s")


def natural_list(items: list[str]) -> str:
    if len(items) < 2:
        return "".join(items)
    if len(items) == 2:
        return " and ".join(items)
    return f"{', '.join(items[:-1])}, and {items[-1]}"


def nav_link(output_path: str, target: str, label: str, active: bool) -> str:
    marker = ' aria-current="page"' if active else ""
    return f'<a href="{esc(href(output_path, target))}"{marker}>{esc(label)}</a>'


def layout(
    *,
    output_path: str,
    title: str,
    description: str,
    active: str,
    content: str,
    site: dict,
) -> str:
    full_title = site["full_name"]
    page_title = full_title if title == full_title else f"{title} | {site['name']}"
    nav = "".join(
        [
            f"<li>{nav_link(output_path, 'index.html', 'Home', active == 'home')}</li>",
            f"<li>{nav_link(output_path, 'research/index.html', 'Research', active == 'research')}</li>",
            f"<li>{nav_link(output_path, 'about/index.html', 'About', active == 'about')}</li>",
            f"<li>{nav_link(output_path, 'contact/index.html', 'Contact', active == 'contact')}</li>",
        ]
    )
    css = href(output_path, "assets/site.css")
    js = href(output_path, "assets/countdown.js")
    home = href(output_path, "index.html")
    email = esc(site["contact_email"])
    return f"""<!doctype html>
<!-- Generated by scripts/build_site.py; edit data/site.json or the generator. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{esc(page_title)}</title>
  <meta name="description" content="{esc(description)}">
  <link rel="canonical" href="{esc(public_url(output_path))}">
  <link rel="stylesheet" href="{esc(css)}">
  <script src="{esc(js)}" defer></script>
</head>
<body>
  <a class="skip-link" href="#main">Skip to main content</a>
  <header class="site-header">
    <div class="header-inner">
      <a class="site-mark" href="{esc(home)}">
        <span class="site-mark-kicker">TJHSST</span>
        <span>Astronomy &amp; Astrophysics Research</span>
      </a>
      <nav aria-label="Primary navigation">
        <ul>{nav}</ul>
      </nav>
    </div>
  </header>
  <main id="main">{content}</main>
  <footer class="site-footer">
    <div>
      <p><strong>{esc(full_title)}</strong><br>Thomas Jefferson High School for Science and Technology</p>
      <p><a href="mailto:{email}">Contact the lab director</a></p>
    </div>
    <p class="footer-note">Public research records and retained student work from the TJHSST Astronomy &amp; Astrophysics Research Lab.</p>
  </footer>
</body>
</html>
"""


def countdown(site: dict) -> str:
    return f"""<div class="tjstar-marker">
  <p class="rail-label">Next tjSTAR</p>
  <time datetime="{esc(site['tjstar_datetime'])}">{esc(site['tjstar_display'])}</time>
  <span class="countdown" data-tjstar-countdown="{esc(site['tjstar_datetime'])}" aria-hidden="true"></span>
  <a href="{esc(site['tjstar_url'])}">Astronomy presentations</a>
</div>"""


def project_card(project: dict, output_path: str, heading_level: int = 3) -> str:
    target = f"{project['year']}/{project['slug']}/index.html"
    artifact_labels = " · ".join(esc(item["label"]) for item in project["artifacts"])
    return f"""<article class="project-card">
  <p class="project-topic">{esc(project['topic'])}</p>
  <h{heading_level}><a href="{esc(href(output_path, target))}">{esc(project['title'])}</a></h{heading_level}>
  <p>{esc(project['summary'])}</p>
  <p class="project-availability">Available: {artifact_labels} · tjSTAR record</p>
</article>"""


