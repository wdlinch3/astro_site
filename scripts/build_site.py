def render_all(data: dict) -> dict[str, str]:
    site = data["site"]
    specifications = [
        (*home_page(data), "home"),
        (*research_page(data), "research"),
        (*about_page(data), "about"),
        (*partners_page(data), "partners"),
        (*labs_page(data), "labs"),
        (*contact_page(data), "contact"),
    ]
    specifications.extend((*year_page(data, year), "research") for year in data["years"])
    specifications.extend((*project_page(data, project), "research") for project in data["projects"])
    rendered: dict[str, str] = {}
    for output_path, title, description, content, active in specifications:
        rendered[output_path] = layout(
            output_path=output_path,
            title=title,
            description=description,
            active=active,
            content=content,
            site=site,
        )
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated pages are missing or stale")
    args = parser.parse_args()
    rendered = render_all(load_data())
    stale: list[str] = []
    for relative, contents in rendered.items():
        destination = ROOT / relative
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != contents:
                stale.append(relative)
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(contents, encoding="utf-8")
        print(f"generated {relative}")
    if stale:
        print("Generated pages are stale or missing:", file=sys.stderr)
        for relative in stale:
            print(f"  {relative}", file=sys.stderr)
        return 1
    if args.check:
        expected = set(rendered)
        for page in ROOT.rglob("*.html"):
            relative = page.relative_to(ROOT).as_posix()
            if "Generated by scripts/build_site.py" in page.read_text(encoding="utf-8") and relative not in expected:
                print(f"Orphan generated page: {relative}", file=sys.stderr)
                return 1
        print(f"All {len(rendered)} generated HTML pages are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
