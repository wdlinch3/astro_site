def research_page(data: dict) -> tuple[str, str, str, str]:
    site = data["site"]
    output = "research/index.html"
    latest_slug = site["latest_year"]
    latest_year = year_definition(data, latest_slug)
    latest_projects = projects_for_year(data, latest_slug)
    latest_topics = list(dict.fromkeys(project["topic"].lower() for project in latest_projects))
    earlier_years = [year for year in reversed(data["years"]) if year["slug"] != latest_slug]
    archive_links = "\n".join(
        f'<a class="year-link compact-year-link" href="{esc(href(output, f"{year["slug"]}/index.html"))}"><span>{esc(year["label"])}</span><small>{len(projects_for_year(data, year["slug"]))} {noun(len(projects_for_year(data, year["slug"])), "project record")}</small></a>'
        for year in earlier_years
    )
    earlier_archives = f'<div class="year-list" aria-label="Earlier research years">{archive_links}</div>' if archive_links else ""
    content = f"""
<div class="page-shell">
  <header class="page-heading">
    <p class="eyebrow">Research</p>
    <h1>Browse the lab's work</h1>
    <p class="lede">Annual records collect concise accounts of the scientific question, method, and result, with retained papers and posters available as supporting artifacts.</p>
  </header>
  <div class="research-index-grid">
    <section class="year-feature" aria-labelledby="year-title">
      <p class="rail-label">Latest available year</p>
      <h2 id="year-title">{esc(latest_year['label'])} research</h2>
      <p>{len(latest_projects)} {noun(len(latest_projects), 'project')} spanning {esc(natural_list(latest_topics))}.</p>
      <a class="button primary" href="{esc(href(output, f'{latest_slug}/index.html'))}">Open the {esc(latest_year['label'])} archive</a>
{earlier_archives}
    </section>
    <aside class="research-rail research-index-rail" aria-label="Research events">
      {countdown(site)}
    </aside>
  </div>
</div>"""
    return output, "Research", "Browse annual research records from the TJHSST Astronomy & Astrophysics Research Lab.", content


