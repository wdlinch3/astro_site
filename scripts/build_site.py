def artifact_link(item: dict, output_path: str) -> str:
    target = ROOT / item["path"]
    suffix = target.suffix.removeprefix(".").upper()
    size_mb = target.stat().st_size / (1024 * 1024)
    details = f"{suffix} · {size_mb:.1f} MB"
    return f'<a class="artifact-link" href="{esc(href(output_path, item["path"]))}"><span>{esc(item["label"])}</span><small>{esc(details)}</small></a>'


