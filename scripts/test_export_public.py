#!/usr/bin/env python3
"""Exercise preservation boundaries with tiny committed repository fixtures."""
import json
from pathlib import Path
import subprocess
import tempfile
import unittest

from export_public import Snapshot, export


def repository(root, files):
    root.mkdir()
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    for name, content in files.items():
        destination = root / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content)
    subprocess.run(["git", "-C", str(root), "add", "."], check=True)
    subprocess.run(["git", "-C", str(root), "-c", "user.name=Export test", "-c", "user.email=test@example.invalid", "commit", "-qm", "fixture"], check=True)
    return Snapshot(root, "HEAD")


PAGE = '<!-- Generated by scripts/build_site.py -->\n<h1 id="main">Lab</h1>'


class ExportTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)

    def test_frozen_revision_includes_only_linked_public_files(self):
        lab = repository(self.root / "lab", {"index.html": PAGE + '<a href="paper.pdf">Paper</a>', "paper.pdf": "public paper", "private.qmd": "private", "unlinked.pdf": "unreviewed"})
        (lab.root / "paper.pdf").write_text("uncommitted change")
        (lab.root / "untracked.pdf").write_text("do not copy")
        manifest = export(lab, self.root / "out")
        self.assertEqual(set(manifest["files"]), {"index.html", "paper.pdf"})
        self.assertEqual((self.root / "out/paper.pdf").read_text(), "public paper")
        self.assertEqual(manifest["sources"]["lab"]["commit"], lab.commit)

    def test_missing_untracked_or_private_references_fail_without_output(self):
        for index, path in enumerate(["missing.pdf", "private.qmd", "../private.pdf"]):
            with self.subTest(path=path):
                lab = repository(self.root / f"lab{index}", {"index.html": PAGE + f'<a href="{path}">Link</a>', "private.qmd": "private"})
                (lab.root / "missing.pdf").write_text("untracked")
                destination = self.root / f"out{index}"
                # Parent traversal leaves /astro/ and is an external URL; local
                # private/missing references must fail rather than enter payload.
                if path.startswith("../"):
                    manifest = export(lab, destination)
                    self.assertEqual(len(manifest["files"]), 1)
                    self.assertIn("https://activities.tjhsst.edu/private.pdf", [d["url"] for d in manifest["external_dependencies"]])
                else:
                    with self.assertRaises(ValueError):
                        export(lab, destination)
                    self.assertFalse(destination.exists())

    def test_school_readings_return_to_local_catalog_and_keep_math(self):
        lab = repository(self.root / "lab", {"index.html": PAGE + '<a href="https://astro2627.sites.tjhsst.edu/teaching/minicourses/reading.html">Read</a>', "minicourses/index.html": PAGE})
        school = repository(self.root / "school", {
            "scripts/minicourses.json": json.dumps({"files": ["teaching/minicourses/reading.html", "teaching/minicourses/reading.pdf"]}),
            "assets/css/aa_packet_theme.css": "body { color: white; }",
            "teaching/minicourses/reading.html": '<h1 id="math">\\(x+y\\)</h1><a href="https://activities.tjhsst.edu/astro/minicourses/">Catalog</a><a href="/teaching/minicourses/reading.pdf">PDF</a><link href="/assets/css/aa_packet_theme.css" rel="stylesheet"><script src="https://cdn.example/math.js"></script>',
            "teaching/minicourses/reading.pdf": "PDF bytes",
        })
        manifest = export(lab, self.root / "out", school)
        reading = (self.root / "out/school/teaching/minicourses/reading.html").read_text()
        self.assertIn('href="../../../minicourses/index.html"', reading)
        self.assertIn('href="reading.pdf"', reading)
        self.assertIn('href="../../assets/css/aa_packet_theme.css"', reading)
        self.assertIn('\\(x+y\\)', reading)
        self.assertEqual((self.root / "out/school/teaching/minicourses/reading.pdf").read_text(), "PDF bytes")
        self.assertEqual(manifest["external_dependencies"][0]["kind"], "runtime")

    def test_missing_fragment_and_symlink_fail(self):
        lab = repository(self.root / "lab", {"index.html": PAGE + '<a href="#missing">Missing</a>'})
        with self.assertRaisesRegex(ValueError, "Missing fragment"):
            export(lab, self.root / "out")
        (lab.root / "index.html").write_text(PAGE + '<a href="linked.pdf">Link</a>')
        (lab.root / "linked.pdf").symlink_to("/tmp/secret.pdf")
        subprocess.run(["git", "-C", str(lab.root), "add", "."], check=True)
        subprocess.run(["git", "-C", str(lab.root), "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-qm", "symlink"], check=True)
        with self.assertRaisesRegex(ValueError, "symlink"):
            export(Snapshot(lab.root, "HEAD"), self.root / "out")

    def test_existing_output_is_never_overwritten(self):
        lab = repository(self.root / "lab", {"index.html": PAGE})
        output = self.root / "out"
        output.mkdir()
        (output / "keep.txt").write_text("keep")
        with self.assertRaisesRegex(ValueError, "empty"):
            export(lab, output)
        self.assertEqual((output / "keep.txt").read_text(), "keep")

    def test_only_configured_course_routes_are_mapped(self):
        lab = repository(self.root / "lab", {"index.html": PAGE + '<a href="https://astro2627.sites.tjhsst.edu/">AA</a><a href="https://astro2627.sites.tjhsst.edu/ss/2026-2027/">Class</a><a href="https://astro2627.sites.tjhsst.edu/unknown/">Unknown</a>'})
        manifest = export(lab, self.root / "out", personal_course_base="https://wdlinch3.github.io/aa/")
        page = (self.root / "out/index.html").read_text()
        self.assertIn('href="https://wdlinch3.github.io/aa/ss/2026-2027/"', page)
        self.assertIn('href="https://astro2627.sites.tjhsst.edu/unknown/"', page)
        self.assertEqual(len(manifest["personal_course_link_mappings"]), 2)
        self.assertTrue(any(item["kind"] == "personal_course_navigation" for item in manifest["external_dependencies"]))

    def test_export_is_reproducible_and_rewrites_canonical(self):
        lab = repository(self.root / "lab", {"index.html": PAGE + '<link rel="canonical" href="https://activities.tjhsst.edu/astro/">'})
        a = export(lab, self.root / "a")
        b = export(lab, self.root / "b")
        self.assertEqual(a, b)
        self.assertIn('href="https://wdlinch3.github.io/astro/"', (self.root / "a/index.html").read_text())


if __name__ == "__main__":
    unittest.main()
